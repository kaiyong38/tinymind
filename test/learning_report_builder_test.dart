import 'package:flutter_test/flutter_test.dart';
import 'package:tinymind/models/learning.dart';
import 'package:tinymind/services/learning_report_builder.dart';
import 'package:tinymind/services/learning_report_pdf.dart';

void main() {
  test('builds report totals and rule-based strongest and practice areas', () {
    final progress = UserProgress(
      childName: 'Sunny',
      childAge: 5,
      totalQuestions: 40,
      correctAnswers: 26,
      moduleAnswered: {
        'letters': 10,
        'numbers': 12,
        'shapes': 8,
        'colors': 10,
      },
      moduleCorrect: {
        'letters': 9,
        'numbers': 7,
        'shapes': 4,
        'colors': 6,
      },
      dailyStats: {
        '2026-09-01': [4, 3],
        '2026-09-03': [5, 4],
        '2026-09-04': [2, 2],
      },
      activityStars: {
        'letters_a': 3,
        'letters_e': 2,
        'numbers_01': 1,
        'shapes_01': 2,
      },
    );

    final report = ReportBuilder.build(
      progress,
      generatedAt: DateTime(2026, 10, 4),
    );

    expect(report.nickname, 'Sunny');
    expect(report.age, 5);
    expect(report.reportDate, '2026-10-04');
    expect(report.daysPlayed, 3);
    expect(report.totalQuestions, 40);
    expect(report.correctAnswers, 26);
    expect(report.overallAccuracy, 0.65);
    expect(report.worlds.map((world) => world.name), [
      'Letter Land',
      'Math Town',
      'Shape Safari',
      'Color Garden',
    ]);
    final letters = report.worlds.first;
    expect(letters.completedActivities, 2);
    expect(letters.stars, 5);
    expect(letters.accuracyPercent, 90);
    expect(report.strongestArea?.name, 'Letter Land');
    expect(report.needsMorePractice?.name, 'Shape Safari');
    expect(report.strongestAreaSummary,
        'Strongest area: Letter Land (90% correct).');
    expect(report.needsMorePracticeSummary,
        'Needs more practice: Shape Safari (50% correct).');

    final text = report.toPlainText();
    expect(text, contains('Overall accuracy: 65% correct'));
    expect(text, contains('90% correct'));
    expect(text, isNot(contains('% accuracy')));
    expect(text, contains('Nickname: Sunny'));
    expect(text, contains('Days played: 3'));
    expect(text, contains('Generated by TinyMind on 2026-10-04.'));
    expect(text, isNot(contains('@')));
  });

  test('requires five questions before naming a practice area', () {
    final report = ReportBuilder.build(
      UserProgress(
        moduleAnswered: {'letters': 4},
        moduleCorrect: {'letters': 1},
      ),
      generatedAt: DateTime(2026, 10, 4),
    );

    expect(report.strongestArea?.name, 'Letter Land');
    expect(report.needsMorePractice, isNull);
    expect(report.needsMorePracticeSummary,
        'Needs more practice: Not enough data yet.');
  });

  test('generates a PDF report', () async {
    final report = ReportBuilder.build(
      UserProgress(childName: 'Sunny'),
      generatedAt: DateTime(2026, 10, 4),
    );

    final bytes = await LearningReportPdf.build(report);

    expect(String.fromCharCodes(bytes.take(5)), '%PDF-');
  });
}
