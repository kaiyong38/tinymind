import '../models/activities.dart';
import '../models/learning.dart';

class LearningReport {
  const LearningReport({
    required this.nickname,
    required this.age,
    required this.reportDate,
    required this.daysPlayed,
    required this.totalQuestions,
    required this.correctAnswers,
    required this.worlds,
    required this.strongestArea,
    required this.needsMorePractice,
  });

  final String nickname;
  final int age;
  final String reportDate;
  final int daysPlayed;
  final int totalQuestions;
  final int correctAnswers;
  final List<LearningWorldReport> worlds;
  final LearningWorldReport? strongestArea;
  final LearningWorldReport? needsMorePractice;

  double get overallAccuracy =>
      totalQuestions == 0 ? 0 : correctAnswers / totalQuestions;

  String get strongestAreaSummary => strongestArea == null
      ? 'Strongest area: Not enough data yet.'
      : 'Strongest area: ${strongestArea!.name} '
          '(${strongestArea!.accuracyPercent}% correct).';

  String get needsMorePracticeSummary => needsMorePractice == null
      ? 'Needs more practice: Not enough data yet.'
      : 'Needs more practice: ${needsMorePractice!.name} '
          '(${needsMorePractice!.accuracyPercent}% correct).';

  String toPlainText() {
    final lines = <String>[
      'TinyMind Learning Report',
      '',
      'Nickname: $nickname',
      'Age: $age',
      'Report date: $reportDate',
      '',
      'Days played: $daysPlayed',
      'Total questions: $totalQuestions',
      'Overall accuracy: ${_percent(overallAccuracy)}% correct',
      '',
      'By learning world',
    ];
    for (final world in worlds) {
      lines.add(
        '${world.name}: ${world.completedActivities}/${world.totalActivities} '
        'activities, ${world.stars}/${world.totalStars} stars, '
        '${world.accuracyPercent}% correct',
      );
    }
    lines
      ..add('')
      ..add(strongestAreaSummary)
      ..add(needsMorePracticeSummary)
      ..add('')
      ..add('Generated by TinyMind on $reportDate.');
    return lines.join('\n');
  }
}

class LearningWorldReport {
  const LearningWorldReport({
    required this.name,
    required this.completedActivities,
    required this.totalActivities,
    required this.stars,
    required this.totalStars,
    required this.answered,
    required this.correct,
  });

  final String name;
  final int completedActivities;
  final int totalActivities;
  final int stars;
  final int totalStars;
  final int answered;
  final int correct;

  double get accuracy => answered == 0 ? 0 : correct / answered;
  int get accuracyPercent => _percent(accuracy);
}

class ReportBuilder {
  const ReportBuilder._();

  static LearningReport build(
    UserProgress progress, {
    DateTime? generatedAt,
  }) {
    final worlds = [
      for (final module in learningModules)
        _buildWorld(progress, module),
    ];
    final tried = worlds.where((world) => world.answered > 0).toList();
    final practiceCandidates =
        worlds.where((world) => world.answered >= 5).toList();

    LearningWorldReport? highestAccuracy;
    LearningWorldReport? lowestWithEnoughData;
    for (final world in tried) {
      if (highestAccuracy == null || world.accuracy > highestAccuracy.accuracy) {
        highestAccuracy = world;
      }
    }
    for (final world in practiceCandidates) {
      if (lowestWithEnoughData == null ||
          world.accuracy < lowestWithEnoughData.accuracy) {
        lowestWithEnoughData = world;
      }
    }

    final date = generatedAt ?? DateTime.now();
    final dateString = '${date.year.toString().padLeft(4, '0')}-'
        '${date.month.toString().padLeft(2, '0')}-'
        '${date.day.toString().padLeft(2, '0')}';
    return LearningReport(
      nickname: progress.childName,
      age: progress.childAge,
      reportDate: dateString,
      daysPlayed: progress.daysLearned,
      totalQuestions: progress.totalQuestions,
      correctAnswers: progress.correctAnswers,
      worlds: worlds,
      strongestArea: highestAccuracy,
      needsMorePractice: lowestWithEnoughData,
    );
  }

  static LearningWorldReport _buildWorld(
    UserProgress progress,
    LearningModule module,
  ) {
    final activities = worldCatalogs[module.id]!.activities;
    return LearningWorldReport(
      name: module.title,
      completedActivities: activities
          .where((activity) => (progress.activityStars[activity.id] ?? 0) > 0)
          .length,
      totalActivities: activities.length,
      stars: activities.fold<int>(
        0,
        (total, activity) => total + (progress.activityStars[activity.id] ?? 0),
      ),
      totalStars: activities.length * 3,
      answered: progress.moduleAnswered[module.id] ?? 0,
      correct: progress.moduleCorrect[module.id] ?? 0,
    );
  }
}

int _percent(double value) => (value * 100).round();
