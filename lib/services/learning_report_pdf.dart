import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import 'learning_report_builder.dart';

class LearningReportPdf {
  const LearningReportPdf._();

  static Future<Uint8List> build(LearningReport report) async {
    final document = pw.Document();
    final bodyStyle = pw.TextStyle(fontSize: 10);
    document.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(36),
        build: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              'TinyMind Learning Report',
              style: pw.TextStyle(fontSize: 21, fontWeight: pw.FontWeight.bold),
            ),
            pw.SizedBox(height: 12),
            pw.Text(
              'Nickname: ${report.nickname}     Age: ${report.age}     '
              'Report date: ${report.reportDate}',
              style: bodyStyle,
            ),
            pw.SizedBox(height: 14),
            pw.Wrap(
              spacing: 24,
              runSpacing: 6,
              children: [
                pw.Text('Days played: ${report.daysPlayed}', style: bodyStyle),
                pw.Text(
                  'Total questions: ${report.totalQuestions}',
                  style: bodyStyle,
                ),
                pw.Text(
                  'Overall accuracy: '
                  '${(report.overallAccuracy * 100).round()}%',
                  style: bodyStyle,
                ),
              ],
            ),
            pw.SizedBox(height: 16),
            pw.Text(
              'By learning world',
              style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold),
            ),
            pw.SizedBox(height: 6),
            pw.TableHelper.fromTextArray(
              headers: const [
                'Learning world',
                'Activities',
                'Stars',
                'Accuracy',
              ],
              data: [
                for (final world in report.worlds)
                  [
                    world.name,
                    '${world.completedActivities}/${world.totalActivities}',
                    '${world.stars}/${world.totalStars}',
                    world.answered == 0
                        ? 'Not tried'
                        : '${world.accuracyPercent}%',
                  ],
              ],
              headerStyle:
                  pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold),
              cellStyle: bodyStyle,
              cellPadding: const pw.EdgeInsets.symmetric(
                horizontal: 7,
                vertical: 6,
              ),
              border: pw.TableBorder.all(
                color: PdfColors.grey400,
                width: 0.5,
              ),
            ),
            pw.SizedBox(height: 16),
            pw.Text(report.strongestAreaSummary, style: bodyStyle),
            pw.SizedBox(height: 6),
            pw.Text(report.needsMorePracticeSummary, style: bodyStyle),
            pw.Spacer(),
            pw.Divider(color: PdfColors.grey400),
            pw.Text(
              'Generated by TinyMind on ${report.reportDate}.',
              style: pw.TextStyle(fontSize: 9, color: PdfColors.grey700),
            ),
          ],
        ),
      ),
    );
    return document.save();
  }
}
